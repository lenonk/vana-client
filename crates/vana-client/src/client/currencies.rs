#[cfg(test)]
mod tests {
    use super::*;

    /// Appendix A: the plans are 9-bit fields of the u64 at 0xd8; Tutelary straddles the two words.
    #[test]
    fn plans() {
        let mut p = vec![0u8; 0x100];
        let v: u64 = 3 | 5 << 9 | 7 << 18 | 300 << 27 | 511 << 36;
        p[0xd8..0xe0].copy_from_slice(&v.to_le_bytes());
        let got: Vec<i64> = MODE1[69..74].iter().map(|&r| read(&p, r)).collect();
        assert_eq!(got, [3, 5, 7, 300, 511]);
        assert_eq!((MODE1.len(), MODE2.len()), (99, 97));
    }
}
