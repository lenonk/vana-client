//! statcom2 rows 6 / 10, Currencies and Currencies 2 (FUN_1022a620 mode 1 / 2; spec
//! ~/ffxi/lab/research/status_rows_spec.md 3): "menu    evitem" listing the fields of s2c 0x113 / 0x118, asked for
//! with c2s 0x10F / 0x115 until one comes.

use super::World;
use super::game_ui::GameUi;
use crate::audio::Ui;

const WINDOW: &str = "menu    evitem";
const WHITE: u32 = 0x8080_8080;
const CURSOR: u32 = 0x8080_3040;
const ROWS: usize = 8;

pub struct Currencies {
    /// +0x88: 1 or 2.
    pub mode: u8,
    /// The rows' values once the reply came (+0x8a).
    values: Option<Vec<i64>>,
    top: usize,
    cursor: usize,
    /// +0x8b / +0x8c: ticks until the request goes again.
    wait: f32,
}

/// Row tables 0x103862c8 / 0x103865e0 with the fields' packet offsets (FUN_102297c0 / FUN_10229ca0): (offset, kind,
/// label group 0xc, help group 0xe); kind 1 / 2 / 4 = u8 / u16 / u32, 0x80 | shift = 9 bits of the u64 at the offset.
type Row = (u16, u8, u16, u16);

fn rows(mode: u8) -> &'static [Row] {
    if mode == 2 { &MODE2 } else { &MODE1 }
}

/// A row's value from the packet (header included).
fn read(p: &[u8], (off, kind, ..): Row) -> i64 {
    let at = |n: usize| p.get(off as usize..off as usize + n);
    match kind {
        1 => at(1).map_or(0, |b| b[0] as i64),
        2 => at(2).map_or(0, |b| u16::from_le_bytes([b[0], b[1]]) as i64),
        4 => at(4).map_or(0, |b| i32::from_le_bytes([b[0], b[1], b[2], b[3]]) as i64),
        k => at(8).map_or(0, |b| (u64::from_le_bytes(b.try_into().unwrap()) >> (k & 0x7f) & 0x1ff) as i64),
    }
}

/// c2s 0x10F (mode 1) / 0x115 (mode 2), header only.
fn request(w: &World, mode: u8) {
    let id = if mode == 2 { 0x115 } else { 0x10F };
    let _ = w.net.commands.send(super::net::NetCommand::Packet { id, body: Vec::new() });
}

/// FUN_1022a620: evitem in this mode, waiting for its data.
pub fn open(w: &mut World, mode: u8) {
    request(w, mode);
    w.currencies = Some(Currencies { mode, values: None, top: 0, cursor: 0, wait: 31.0 });
}

/// The modern Status page's currencies: both lists asked for at once (again every 31 ticks until each came).
pub fn ask_both(w: &mut World) {
    let Some(s) = w.status.as_mut().filter(|s| s.cur_wait.is_none()) else { return };
    s.cur_wait = Some(31.0);
    request(w, 1);
    request(w, 2);
}

/// Both lists as one: (label, value, help) in retail's order, Currencies then Currencies 2.
pub fn merged(gu: &GameUi, cur: &[Option<Vec<i64>>; 2]) -> Vec<(String, i64, String)> {
    let mut out = Vec::new();
    for (k, values) in cur.iter().enumerate() {
        let Some(values) = values else { continue };
        for (r, v) in rows(k as u8 + 1).iter().zip(values) {
            out.push((gu.lobby_msg(0x0c, r.2 as usize, ""), *v, gu.menu_msg(r.3 as usize, "")));
        }
    }
    out
}

/// Per frame while the data is missing (FUN_1022aca0 / FUN_1022ace0): the request again every 31 ticks.
pub fn update(w: &mut World, ticks: f32) {
    let mut missing = Vec::new();
    if let Some(s) = w.status.as_mut()
        && let Some(t) = s.cur_wait.as_mut()
    {
        *t -= ticks;
        if *t <= 0.0 {
            *t = 31.0;
            missing = (1..=2u8).filter(|&m| s.cur[m as usize - 1].is_none()).collect();
        }
    }
    for m in missing {
        request(w, m);
    }
    let Some(c) = w.currencies.as_mut().filter(|c| c.values.is_none()) else { return };
    c.wait -= ticks;
    if c.wait <= 0.0 {
        c.wait = 31.0;
        let mode = c.mode;
        request(w, mode);
    }
}

/// s2c 0x113 (mode 1) / 0x118 (mode 2): the stored callback once (FUN_10229f00 / FUN_1022a090).
pub fn on_packet(w: &mut World, mode: u8, p: &[u8]) {
    if let Some(s) = w.status.as_mut().filter(|s| s.cur_wait.is_some() && (1..=2).contains(&mode)) {
        s.cur[mode as usize - 1] = Some(rows(mode).iter().map(|&r| read(p, r)).collect());
    }
    let Some(c) = w.currencies.as_mut().filter(|c| c.mode == mode && c.values.is_none()) else { return };
    c.values = Some(rows(mode).iter().map(|&r| read(p, r)).collect());
}

/// FUN_1022aa40: Escape closes; with the data the paged list keys (Up / Down wrap, Left / Right by 8, SE 0001);
/// Enter does nothing.
pub fn key(w: &mut World, key: egui::Key) {
    use egui::Key as K;
    if key == K::Escape {
        w.sounds.push(Ui::Cancel as u32);
        w.currencies = None;
        return;
    }
    let Some(c) = w.currencies.as_mut().filter(|c| c.values.is_some()) else { return };
    let n = rows(c.mode).len();
    match key {
        K::ArrowUp | K::ArrowDown => {
            c.cursor = if key == K::ArrowDown { (c.cursor + 1) % n } else { (c.cursor + n - 1) % n };
            if c.cursor < c.top {
                c.top = c.cursor;
            } else if c.cursor >= c.top + ROWS {
                c.top = c.cursor + 1 - ROWS;
            }
        }
        K::ArrowLeft | K::ArrowRight => {
            let row = c.cursor - c.top;
            let max = n.saturating_sub(ROWS);
            c.top = if key == K::ArrowRight { (c.top + ROWS).min(max) } else { c.top.saturating_sub(ROWS) };
            c.cursor = (c.top + row).min(n - 1);
        }
        _ => return,
    }
    w.sounds.push(Ui::Cursor as u32);
}

/// The scroll bar (Owner::Journal, as the other evitem lists).
pub(super) fn bar(w: &mut World, m: super::scrollbar::Msg) -> bool {
    let Some(c) = w.currencies.as_mut().filter(|c| c.values.is_some()) else { return false };
    let mut row = c.cursor - c.top;
    let moved = super::scrollbar::paged(m, &mut c.top, &mut row, rows(c.mode).len(), ROWS);
    c.cursor = c.top + row;
    moved
}

/// Mouse *(inf: the paged lists' hover)*: hover moves the cursor to a row.
pub fn pointer(w: &mut World, gu: &GameUi, sw: f32, sh: f32, p: (f32, f32), moved: bool) {
    let Some(c) = w.currencies.as_ref().filter(|c| c.values.is_some()) else { return };
    let Some((x, y)) = gu.window_xy(WINDOW, sw, sh) else { return };
    let n = rows(c.mode).len();
    let hit = gu.layout(WINDOW).and_then(|l| {
        l.elements.iter().skip(1).find(|e| {
            let (ex, ey) = (x + e.x as f32, y + e.y as f32);
            p.0 >= ex && p.0 < ex + e.w as f32 && p.1 >= ey && p.1 < ey + e.h as f32
        })
    });
    let Some(row) = hit.map(|e| c.top + e.id as usize - 1).filter(|&r| r < n) else { return };
    gu.hover.set(true);
    if moved && row != c.cursor
        && let Some(c) = w.currencies.as_mut()
    {
        c.cursor = row;
        w.sounds.push(Ui::Cursor as u32);
    }
}

/// Title slot 2 group 0xe 0x2d1 "Currencies" (both modes); help slot 2 the cursor row's help (row 0's before the data).
pub fn bars(gu: &GameUi, w: &World, bars: &mut super::hudtop::BarText) {
    let Some(c) = &w.currencies else { return };
    bars.title[2] = gu.menu_msg(0x2d1, "");
    bars.help[2] = rows(c.mode).get(c.cursor).map_or(String::new(), |r| gu.menu_msg(r.3 as usize, ""));
}

/// LAB_10229f80 / LAB_1022a110 at the layout's row children: framesus 35 at (4, 5), the label in the game font at
/// (18, 0), the value "%d" in fontshp right-aligned at (310, 3); the cursor row 0x80803040. Before the data: the frame
/// only.
pub fn draw(gu: &mut GameUi, w: &World, sw: f32, sh: f32) -> Option<[f32; 4]> {
    let c = w.currencies.as_ref()?;
    let focused = w.confirm.is_none();
    let n = rows(c.mode).len();
    let sel = c.values.is_some().then(|| (c.cursor - c.top + 1) as u16);
    let hide: Vec<u16> = (1..=ROWS as u16).filter(|&k| c.values.is_none() || c.top + k as usize > n).collect();
    let win = gu.lobby_window_off(WINDOW, sw, sh, (0.0, 0.0), sel, focused, &hide)?;
    let Some(values) = &c.values else { return Some(win.frame) };
    for &(id, [cx, cy, ..]) in win.children.iter().filter(|(id, _)| (1..=ROWS as u16).contains(id)) {
        let i = c.top + id as usize - 1;
        let (Some(r), Some(v)) = (rows(c.mode).get(i), values.get(i)) else { continue };
        let tint = if i == c.cursor { CURSOR } else { WHITE };
        gu.sprite("menu    framesus", 35, cx + 4.0, cy + 5.0, WHITE);
        let label = gu.lobby_msg(0x0c, r.2 as usize, "");
        gu.text(&label, cx + 18.0, cy, 0, tint.to_le_bytes());
        gu.shape_text(&v.to_string(), cx + 310.0, cy + 3.0, tint, true);
    }
    let [fx, fy, fw, fh] = win.frame;
    gu.scroll_bar(fx + fw - 8.0, fy, fh, n, ROWS, c.top);
    gu.bar_site(super::scrollbar::Owner::Journal, fx + fw - 8.0, fy, fh, n, ROWS, c.top);
    Some(win.frame)
}

